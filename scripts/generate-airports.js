/**
 * Generates src/features/flights/airports.generated.ts from the OpenFlights
 * reference CSVs in data/extracted/kq-routes-reference/.
 *
 * The list holds every airport in Kenya that has an IATA code, plus every
 * airport that appears in a Kenya Airways (KQ) route in routes.csv.
 *
 * Usage: node scripts/generate-airports.js
 *
 * Data: OpenFlights (https://openflights.org/data.php), Open Database License
 * (ODbL) v1.0; contents under the Database Contents License (DbCL) v1.0.
 * Route data stops in June 2014.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SOURCE_DIR = path.join(ROOT, 'data', 'extracted', 'kq-routes-reference');
const OUTPUT = path.join(ROOT, 'src', 'features', 'flights', 'airports.generated.ts');

/** One CSV line, with double-quoted fields and "" escapes. */
function parseLine(line) {
  const fields = [];
  let current = '';
  let quoted = false;

  for (let i = 0; i < line.length; i += 1) {
    const char = line[i];

    if (quoted) {
      if (char === '"' && line[i + 1] === '"') {
        current += '"';
        i += 1;
      } else if (char === '"') {
        quoted = false;
      } else {
        current += char;
      }
    } else if (char === '"') {
      quoted = true;
    } else if (char === ',') {
      fields.push(current);
      current = '';
    } else {
      current += char;
    }
  }

  fields.push(current);
  return fields;
}

function readCsv(file) {
  const [header, ...rows] = fs
    .readFileSync(path.join(SOURCE_DIR, file), 'utf8')
    .split(/\r?\n/)
    .filter(Boolean)
    .map(parseLine);

  return rows.map((row) => Object.fromEntries(header.map((name, i) => [name, row[i] ?? ''])));
}

const IATA = /^[A-Z]{3}$/;

const airports = readCsv('airports.csv').filter((row) => IATA.test(row.IATA));
const byCode = new Map(airports.map((row) => [row.IATA, row]));

const kqCodes = new Set();
for (const route of readCsv('routes.csv')) {
  if (route.Airline !== 'KQ') continue;
  kqCodes.add(route['Source airport']);
  kqCodes.add(route['Destination airport']);
}

const missing = [...kqCodes].filter((code) => !byCode.has(code));
if (missing.length > 0) {
  console.warn(`KQ route airports missing from airports.csv: ${missing.join(', ')}`);
}

const selected = new Map();
for (const row of airports) {
  if (row.Country === 'Kenya' || kqCodes.has(row.IATA)) selected.set(row.IATA, row);
}

const list = [...selected.values()]
  .map((row) => ({
    code: row.IATA,
    city: row.City.trim(),
    // "Jomo Kenyatta International Airport" -> "Jomo Kenyatta International"
    name: row.Name.trim().replace(/\s+Airport$/i, ''),
    country: row.Country.trim(),
  }))
  .sort((a, b) => {
    const kenya = Number(b.country === 'Kenya') - Number(a.country === 'Kenya');
    return kenya || a.city.localeCompare(b.city) || a.code.localeCompare(b.code);
  });

const kenyan = list.filter((item) => item.country === 'Kenya').length;

const output = `/**
 * GENERATED by scripts/generate-airports.js. Do not edit by hand.
 *
 * ${list.length} airports: ${kenyan} in Kenya with an IATA code, plus every airport in a
 * Kenya Airways (KQ) route in the OpenFlights route data (which stops in June 2014).
 *
 * Derived from the OpenFlights Airport and Route Databases
 * (https://openflights.org/data.php), made available under the Open Database
 * License (ODbL) v1.0 (https://opendatacommons.org/licenses/odbl/1-0/);
 * individual contents under the Database Contents License (DbCL) v1.0.
 * Airport base data: OurAirports and DAFIF (public domain).
 * This derived list is likewise made available under the ODbL v1.0.
 */

export type Airport = {
  /** 3-letter IATA code, as stored on Flights documents. */
  code: string;
  city: string;
  name: string;
  country: string;
};

export const AIRPORTS: readonly Airport[] = ${JSON.stringify(list, null, 2)};
`;

fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
fs.writeFileSync(OUTPUT, output);
console.log(`Wrote ${list.length} airports (${kenyan} in Kenya) to ${path.relative(ROOT, OUTPUT)}`);
